/// Estimates a doctor's gender from their Arabic first name.
///
/// The Lebanese Order of Physicians list has no gender column. Arabic names
/// follow "first name + father's name + family name", so only the first token
/// says anything about the doctor. The lists below cover the ~1,000 most
/// common first names in the dataset (about 90% of doctors). Names used for
/// both men and women (e.g. نور، جود، نهاد، غابي) are intentionally absent and
/// resolve to unknown instead of being guessed.
class DoctorGenderResolver {
  const DoctorGenderResolver._();

  static const String female = 'Female';
  static const String male = 'Male';

  /// Returns [female], [male] or '' when the name is not confidently known.
  static String fromArabicName(String nameAr) {
    final first = _firstName(nameAr);
    if (first.isEmpty) return '';
    if (_female.contains(first)) return female;
    if (_male.contains(first)) return male;
    return '';
  }

  static String _firstName(String nameAr) {
    var cleaned = nameAr.trim();
    cleaned = cleaned.replaceFirst(RegExp(r'^(د\s*\.|الدكتور[ةه]?|دكتور[ةه]?)\s*'), '');
    final tokens = cleaned.split(RegExp(r'\s+')).where((t) => t.isNotEmpty);
    return tokens.isEmpty ? '' : normalizeArabic(tokens.first);
  }

  /// Folds spelling variants so فاطمة/فاطمه and أحمد/احمد compare equal.
  static String normalizeArabic(String value) {
